/**
 * Lemma Central API Configuration Engine
 */
const APIConfigManager = {
    DEFAULT_PROD_URL: 'https://r4hul-78-lemma-backend.hf.space',
    DEFAULT_DEV_URL: 'http://localhost:8000',
    STORAGE_KEY: 'lemma_override_api_url',

    /**
     * Resolves the primary URL used to reach the FastAPI backend.
     * Supports production HF space, standard local dev, Capacitor WebViews,
     * and custom local-network IP overrides for device testing.
     */
    async getApiBaseUrl() {
        // 1. Check for manual developer settings overrides (saved in LocalStorage)
        const localOverride = localStorage.getItem(this.STORAGE_KEY);
        if (localOverride) {
            return localOverride;
        }

        // 2. Detect if running inside a Capacitor/Native WebView container
        const isCapacitor = window.Capacitor !== undefined || window.location.href.startsWith('file:');

        // 3. When FastAPI serves the frontend locally, use the exact browser origin.
        // This avoids hard-coding a port and keeps frontend/backend communication
        // on the same host and port (e.g. localhost:8001 during local development).
        const host = window.location.hostname;
        if (host === 'localhost' || host === '127.0.0.1') {
            if (isCapacitor) {
                return this.DEFAULT_PROD_URL;
            }
            return window.location.origin;
        }

        // 4. Read runtime configurations generated by host deployments (Vercel)
        try {
            const controller = new AbortController();
            const timeoutId = setTimeout(() => controller.abort(), 2000);

            const response = await fetch('config.json', { signal: controller.signal });
            clearTimeout(timeoutId);

            if (response.ok) {
                const configData = await response.json();
                if (configData.BACKEND_API_URL) {
                    return configData.BACKEND_API_URL;
                }
            }
        } catch (e) {
            console.warn("Could not retrieve config.json, using default API:", e);
        }

        return this.DEFAULT_PROD_URL;
    },

    /**
     * Saves a developer-specific API base URL (e.g. http://192.168.1.100:8000)
     */
    setDeveloperOverrideUrl(url) {
        if (!url) {
            localStorage.removeItem(this.STORAGE_KEY);
            return;
        }
        localStorage.setItem(this.STORAGE_KEY, url);
    }
};

/*
 * Issue 18/19: resilient analysis-status transport.
 *
 * app.js intentionally keeps a simple one-second polling loop. Instead of
 * making every tick hit the backend, this wrapper coalesces status requests,
 * applies exponential backoff while a job is running, and retries transient
 * network/5xx failures. After a bounded retry window it returns a terminal
 * "failed" status so the UI cannot remain stuck in an endless polling state.
 */
(function installResilientStatusPolling() {
    if (window.__lemmaResilientPollingInstalled) return;
    window.__lemmaResilientPollingInstalled = true;

    const nativeFetch = window.fetch.bind(window);
    const jobs = new Map();
    const MAX_BACKOFF_MS = 5000;
    const INITIAL_BACKOFF_MS = 1500;
    const MAX_TRANSPORT_FAILURES = 5;
    const REQUEST_TIMEOUT_MS = 8000;

    function isStatusRequest(input) {
        const url = typeof input === "string" ? input : input?.url;
        if (!url) return null;
        const match = url.match(/\/api\/v1\/status\/([^/?#]+)/);
        return match ? { url, jobId: decodeURIComponent(match[1]) } : null;
    }

    function jsonResponse(payload, status = 200) {
        return new Response(JSON.stringify(payload), {
            status,
            headers: { "Content-Type": "application/json" }
        });
    }

    function cachedResponse(state) {
        return jsonResponse(state.lastPayload || {
            status: "pending",
            retryable: true,
            message: "Waiting for the analysis worker..."
        });
    }

    async function fetchStatus(url, init, state) {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

        try {
            const response = await nativeFetch(url, { ...init, signal: controller.signal });
            const payload = await response.clone().json().catch(() => null);

            if (!response.ok) {
                const transient = response.status === 429 || response.status >= 500;
                if (!transient) {
                    return { terminal: true, payload: {
                        status: "failed",
                        error: payload?.detail || `Status request failed (${response.status}).`,
                        retryable: false
                    }};
                }
                throw new Error(payload?.detail || `Status service returned ${response.status}.`);
            }

            state.transportFailures = 0;
            state.backoffMs = INITIAL_BACKOFF_MS;
            state.lastPayload = payload || { status: "processing" };

            if (state.lastPayload.status === "completed" || state.lastPayload.status === "failed") {
                return { terminal: true, payload: state.lastPayload };
            }

            state.nextRequestAt = Date.now() + state.backoffMs;
            state.backoffMs = Math.min(Math.round(state.backoffMs * 1.5), MAX_BACKOFF_MS);
            return { terminal: false, payload: state.lastPayload };
        } catch (error) {
            state.transportFailures += 1;
            if (state.transportFailures >= MAX_TRANSPORT_FAILURES) {
                return {
                    terminal: true,
                    payload: {
                        status: "failed",
                        error: "Unable to reach the analysis status service after several retries. Please try the analysis again.",
                        retryable: false
                    }
                };
            }

            state.nextRequestAt = Date.now() + state.backoffMs;
            state.backoffMs = Math.min(Math.round(state.backoffMs * 1.5), MAX_BACKOFF_MS);

            return {
                terminal: false,
                payload: state.lastPayload || {
                    status: "processing",
                    retryable: true,
                    message: `Temporary status-service failure. Retrying automatically (${state.transportFailures}/${MAX_TRANSPORT_FAILURES})...`
                }
            };
        } finally {
            clearTimeout(timeoutId);
        }
    }

    window.fetch = function resilientFetch(input, init) {
        const statusRequest = isStatusRequest(input);
        if (!statusRequest) {
            return nativeFetch(input, init);
        }

        let state = jobs.get(statusRequest.jobId);
        if (!state) {
            state = {
                nextRequestAt: 0,
                backoffMs: INITIAL_BACKOFF_MS,
                transportFailures: 0,
                lastPayload: null,
                inFlight: null
            };
            jobs.set(statusRequest.jobId, state);
        }

        if (state.inFlight) {
            return state.inFlight.then(result => jsonResponse(result.payload));
        }

        if (Date.now() < state.nextRequestAt && state.lastPayload) {
            return Promise.resolve(cachedResponse(state));
        }

        state.inFlight = fetchStatus(statusRequest.url, init || {}, state);
        return state.inFlight.then(result => {
            if (result.terminal) {
                jobs.delete(statusRequest.jobId);
            }
            return jsonResponse(result.payload);
        }).finally(() => {
            state.inFlight = null;
        });
    };
})();
